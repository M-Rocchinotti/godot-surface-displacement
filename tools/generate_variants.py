#!/usr/bin/env python
"""Write the shader variants in addons/gads/render/shaders/variants/.

Each surface variant is `shader_type spatial;`, its #defines and one #include of
gads_surface.gdshaderinc, so every variant compiles from the same source; the GADSDisplacementField3D
variants (gads_field_*) include gads_field.gdshaderinc the same way. The GADSManager node
swaps a material's shader between the quality variants of the same mapping (flat, pom, pom_ss)
and keeps the depth write, which is a per-material choice. tests/run_logic_tests.gd checks that the files match this
script (run it after changing the table).

    python tools/generate_variants.py            # write the files
    python tools/generate_variants.py --check    # exit 1 if any file differs
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "addons" / "gads" / "render" / "shaders" / "variants"
INCLUDE = "res://addons/gads/render/shaders/gads_surface.gdshaderinc"

MAPPINGS = {
    "uv": ("GADS_MAPPING_UV", "mesh UVs"),
    "world": ("GADS_MAPPING_WORLD", "world-planar XZ"),
    "triplanar": ("GADS_MAPPING_TRIPLANAR", "world triplanar"),
}
QUALITIES = {
    "flat": ([], "normal mapping only"),
    "pom": (["GADS_POM"], "parallax occlusion mapping"),
    "pom_ss": (["GADS_POM", "GADS_SELF_SHADOW"], "parallax occlusion mapping with self-shadowing"),
}


FIELD_INCLUDE = "res://addons/gads/render/shaders/gads_field.gdshaderinc"
# BaseMaterial3D's defaults. A spatial shader without render modes gets Lambert diffuse; the
# self-shadowing light() reproduces Burley, so every variant asks for it (and so they match
# StandardMaterial3D).
RENDER_MODE = "render_mode diffuse_burley, specular_schlick_ggx;\n"


def variants() -> dict[str, str]:
    files = {}
    for quality, (defines, quality_text) in QUALITIES.items():
        name = f"gads_field_{quality}.gdshader"
        text = "// Generated by tools/generate_variants.py - do not edit.\n"
        text += f"// GADS: GADSDisplacementField3D ground geometry, {quality_text}.\n"
        text += "shader_type spatial;\n" + RENDER_MODE + "\n"
        text += "".join(f"#define {d}\n" for d in defines)
        text += f'#include "{FIELD_INCLUDE}"\n'
        files[name] = text
    for layered in (False, True):
        for mapping, (mapping_define, mapping_text) in MAPPINGS.items():
            for quality, (defines, quality_text) in QUALITIES.items():
                for depth in ([False, True] if defines else [False]):
                    # Silhouette POM: UV-mapped props (curved meshes), parallax qualities.
                    for sil in ([False, True] if defines and mapping == "uv" and not layered else [False]):
                        files.update(_surface_variant(layered, mapping, mapping_define, mapping_text, quality, defines, quality_text, depth, sil))
    return files


def _surface_variant(layered: bool, mapping: str, mapping_define: str, mapping_text: str, quality: str, defines: list[str],
                     quality_text: str, depth: bool, sil: bool = False) -> dict[str, str]:
    name = f"gads_{'layered_' if layered else ''}{mapping}_{quality}{'_sil' if sil else ''}{'_depth' if depth else ''}.gdshader"
    all_defines = ((["GADS_LAYERED"] if layered else []) + [mapping_define] + defines + (["GADS_SILHOUETTE"] if sil else [])
                   + (["GADS_DEPTH_WRITE"] if depth else []))
    text = "// Generated by tools/generate_variants.py - do not edit.\n"
    text += f"// GADS: {'up to three layers blended by vertex colour, slope and height, ' if layered else ''}{mapping_text}, {quality_text}"
    text += ", relief in the silhouette" if sil else ""
    text += ", writes depth (expensive, opt-in).\n" if depth else ".\n"
    text += "shader_type spatial;\n" + RENDER_MODE + "\n"
    text += "".join(f"#define {d}\n" for d in all_defines)
    text += f'#include "{INCLUDE}"\n'
    return {name: text}


def main() -> int:
    check = "--check" in sys.argv
    wanted = variants()
    OUT.mkdir(parents=True, exist_ok=True)
    stale = []
    for name, text in wanted.items():
        path = OUT / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(name)
            if not check:
                path.write_text(text, encoding="utf-8", newline="\n")
    extra = sorted(p.name for p in OUT.glob("*.gdshader") if p.name not in wanted)
    if check:
        for name in stale:
            print(f"stale: {name}")
        for name in extra:
            print(f"not generated: {name}")
        return 1 if stale or extra else 0
    for name in extra:
        (OUT / name).unlink()
    print(f"{len(wanted)} variants, {len(stale)} written, {len(extra)} removed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
