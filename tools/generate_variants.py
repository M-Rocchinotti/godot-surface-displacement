#!/usr/bin/env python
"""Write the shader variants in addons/surface_displacement/shaders/variants/.

Each variant is `shader_type spatial;`, its #defines and one #include of sd_surface.gdshaderinc,
so every variant compiles from the same source. The SurfaceDisplacement node swaps a material's
shader between the quality variants of the same mapping (flat, pom, pom_ss) and keeps the depth
write, which is a per-material choice. tests/run_logic_tests.gd checks that the files match this
script (run it after changing the table).

    python tools/generate_variants.py            # write the files
    python tools/generate_variants.py --check    # exit 1 if any file differs
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "addons" / "surface_displacement" / "shaders" / "variants"
INCLUDE = "res://addons/surface_displacement/shaders/sd_surface.gdshaderinc"

MAPPINGS = {
    "uv": ("SD_MAPPING_UV", "mesh UVs"),
    "world": ("SD_MAPPING_WORLD", "world-planar XZ"),
    "triplanar": ("SD_MAPPING_TRIPLANAR", "world triplanar"),
}
QUALITIES = {
    "flat": ([], "normal mapping only"),
    "pom": (["SD_POM"], "parallax occlusion mapping"),
    "pom_ss": (["SD_POM", "SD_SELF_SHADOW"], "parallax occlusion mapping with self-shadowing"),
}


def variants() -> dict[str, str]:
    files = {}
    for mapping, (mapping_define, mapping_text) in MAPPINGS.items():
        for quality, (defines, quality_text) in QUALITIES.items():
            for depth in ([False, True] if defines else [False]):
                name = f"sd_{mapping}_{quality}{'_depth' if depth else ''}.gdshader"
                all_defines = [mapping_define] + defines + (["SD_DEPTH_WRITE"] if depth else [])
                text = "// Generated by tools/generate_variants.py - do not edit.\n"
                text += f"// Surface Displacement: {mapping_text}, {quality_text}"
                text += ", writes depth (expensive, opt-in).\n" if depth else ".\n"
                text += "shader_type spatial;\n\n"
                text += "".join(f"#define {d}\n" for d in all_defines)
                text += f'#include "{INCLUDE}"\n'
                files[name] = text
    return files


def main() -> int:
    check = "--check" in sys.argv
    wanted = variants()
    OUT.mkdir(parents=True, exist_ok=True)
    stale = []
    for name, text in wanted.items():
        path = OUT / name
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(name)
            if not check:
                path.write_text(text, encoding="utf-8", newline="\n")
    extra = sorted(p.name for p in OUT.glob("*.gdshader") if p.name not in wanted)
    if check:
        for name in stale:
            print(f"stale: {name}")
        for name in extra:
            print(f"not generated: {name}")
        return 1 if stale or extra else 0
    for name in extra:
        (OUT / name).unlink()
    print(f"{len(wanted)} variants, {len(stale)} written, {len(extra)} removed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
